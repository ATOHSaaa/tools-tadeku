import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { inferDims } from './lib/hontai-wikipedia.mjs';
import { QUESTIONS } from './hajimete-hon-questions.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const dataPath = path.join(root, 'shared/hajimete-hon-data.js');
const DIMENSIONS = ['easy', 'fun', 'deep', 'pace', 'short', 'real'];

const ctx = { window: {} };
ctx.window = ctx;
vm.runInNewContext(fs.readFileSync(dataPath, 'utf8'), ctx);

const { BOOKS, meta } = ctx.window.HajimeteHonData;
const books = BOOKS.map((book) => ({
  ...book,
  dims: inferDims(book.name, book.hontai, book.author, book.synopsis || ''),
}));

const nextMeta = {
  ...meta,
  dimsReinferredAt: new Date().toISOString(),
};

const output = `/* generated by scripts/build-hajimete-hon-data.mjs — do not edit by hand */
(function () {
  const DIMENSIONS = ${JSON.stringify(DIMENSIONS, null, 2)};

  const BOOKS = ${JSON.stringify(books, null, 2)};

  const QUESTIONS = ${JSON.stringify(QUESTIONS, null, 2)};

  window.HajimeteHonData = {
    DIMENSIONS,
    BOOKS,
    QUESTIONS,
    meta: ${JSON.stringify(nextMeta, null, 6)},
  };
})();
`;

fs.writeFileSync(dataPath, output, 'utf8');
console.log(`Re-inferred dims for ${books.length} books -> ${dataPath}`);
